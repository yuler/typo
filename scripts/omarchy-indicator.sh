#!/bin/bash
set -euo pipefail

# Hyprland (Omarchy) window rule: float the Typo indicator, keep its size, and
# park it in the bottom-right corner.

warn() {
    echo "⚠️  [WARN] $*" >&2
}

HYPR_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/hypr"
HYPR_CONFIG="$HYPR_DIR/hyprland.lua"
RULE_FILE="$HYPR_DIR/typo.lua"
REQUIRE_LINE='require("hypr.typo")'

WIDTH=""
HEIGHT=""
MARGIN=20

while [[ "$#" -gt 0 ]]; do
    case $1 in
        --width) WIDTH="$2"; shift 2 ;;
        --height) HEIGHT="$2"; shift 2 ;;
        --margin) MARGIN="$2"; shift 2 ;;
        --help|-h)
            echo "Usage: $0 [OPTIONS]"
            echo ""
            echo "Options:"
            echo "  --width N    Indicator width (default: current window width, or 204)"
            echo "  --height N   Indicator height (default: current window height, or 51)"
            echo "  --margin N   Gap from the bottom-right corner in px (default: 20)"
            echo "  --help, -h   Show this help message and exit"
            exit 0
            ;;
        *) echo "Unknown parameter passed: $1" >&2; exit 1 ;;
    esac
done

if ! command -v hyprctl >/dev/null 2>&1; then
    echo "hyprctl not found. This script is for Hyprland (Omarchy)." >&2
    exit 1
fi

if [[ ! -f "$HYPR_CONFIG" ]]; then
    echo "$HYPR_CONFIG not found. Omarchy with a Lua Hyprland config is required." >&2
    exit 1
fi

# Default to the size the indicator has right now.
if [[ -z "$WIDTH" || -z "$HEIGHT" ]]; then
    current=""
    if command -v jq >/dev/null 2>&1; then
        current=$(hyprctl clients -j | jq -r '.[] | select(.class == "Typo" and .title == "typo - Indicator") | "\(.size[0]) \(.size[1])"' | head -n 1)
    else
        warn "jq not found; cannot read the current indicator size."
    fi
    if [[ -n "$current" ]]; then
        read -r current_width current_height <<< "$current"
    else
        warn "Typo indicator is not open; using the default size."
        current_width=204
        current_height=51
    fi
    WIDTH="${WIDTH:-$current_width}"
    HEIGHT="${HEIGHT:-$current_height}"
fi

# window_w/window_h in move are the pre-rule size, so bake in the target size.
cat > "$RULE_FILE" <<EOF
-- Generated by typo scripts/omarchy-indicator.sh. Re-run it to update.
o.window({ class = "^[tT]ypo\$", title = "^typo - Indicator\$" }, {
  float = true,
  pin = true,
  size = { $WIDTH, $HEIGHT },
  move = { "(monitor_w-$((WIDTH + MARGIN)))", "(monitor_h-$((HEIGHT + MARGIN)))" },
  no_initial_focus = true,
  focus_on_activate = false,
  suppress_event = "activate activatefocus",
})
EOF

if ! grep -qF "$REQUIRE_LINE" "$HYPR_CONFIG"; then
    printf '\n-- Typo indicator window rule.\n%s\n' "$REQUIRE_LINE" >> "$HYPR_CONFIG"
fi

hyprctl reload >/dev/null

echo ""
echo "============================================="
echo "  ✅ Typo indicator rule configured"
echo "============================================="
echo "  Rule file  $RULE_FILE"
echo "  Size       ${WIDTH}x${HEIGHT}"
echo "  Position   bottom-right, ${MARGIN}px margin"
echo "============================================="
echo "  Restart typo to apply it to the open indicator."
echo ""
